-- Миграция — индексы под списки панели (замеры на 500 тысячах строк журнала и 75 тысячах заявок).
--
--   · app.audit_log (at desc, id desc): страница журнала «новые сверху» (GET /staff/audit —
--     order by at desc, id desc limit N) читалась сортировкой всей таблицы: около секунды на
--     500 тысячах строк. По этому индексу — первые N строк за единицы миллисекунд, а число записей
--     API считает отдельным запросом, и только когда его не видно по странице (раньше —
--     count(*) over (), которому индекс не помогал).
--     Существующие audit_log_object и audit_log_actor ведут от вида и id объекта или актора —
--     к списку без фильтров они не подходят.
--
-- Откат: supabase/rollbacks/20261012110000_perf_indexes.down.sql
-- ════════════════════════════════════════════════════════════════════════════

create index audit_log_at_id on app.audit_log (at desc, id desc);
comment on index app.audit_log_at_id is
  'Журнал в панели: новые сверху (order by at desc, id desc) без сортировки всей таблицы';
