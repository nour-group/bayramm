/** Слова, которых нет в текстах клиента (кроме общих запретов «брон…» — их проверяют отдельно) */
export const GLOSSARY_FORBIDDEN = {
  ru: [/вендор/i, /подрядчик/i],
  uz: [/\bariza/i, /akkaunt/i, /\bvendor/i],
} as const;

// «вендор» во всех падежах → «исполнитель» в том же падеже и числе (оба — мужского рода)
const VENDOR_RU = /([Вв])ендор(ами|ам|ах|ов|ом|ы|у|а|е)?(?![а-яё])/g;
const EXECUTOR_ENDINGS: Readonly<Record<string, string>> = {
  "": "ь",
  а: "я",
  у: "ю",
  ом: "ем",
  е: "е",
  ы: "и",
  ов: "ей",
  ам: "ям",
  ами: "ями",
  ах: "ях",
};

// Перед гласной «о» становится «об»: «О вендоре» → «Об исполнителе»
const ABOUT_RU = /(^|[^а-яё])([Оо]) (?=исполнител)/gi;

/** Текст по глоссарию: «вендор» → «исполнитель» с тем же падежом и заглавной буквой */
export function glossaryRu(text: string): string {
  return text
    .replace(
      VENDOR_RU,
      (_, first: string, ending = "") =>
        `${first === "В" ? "И" : "и"}сполнител${EXECUTOR_ENDINGS[ending] ?? "ь"}`,
    )
    .replace(ABOUT_RU, "$1$2б ");
}
