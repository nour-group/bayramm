import type { ru } from "./ru";

/**
 * Словарь клиентского приложения. Тип выводится из русского словаря, узбекский
 * объявлен этим типом — лишний, пропущенный или другого вида ключ не скомпилируется.
 * Число параметров у функций TS не сверяет (функция с меньшим числом подходит),
 * это проверяет тест i18n.test.ts.
 */
export type Dict = { readonly [K in keyof typeof ru]: (typeof ru)[K] };

/** Ключ словаря */
export type DictKey = keyof Dict;

/** Язык интерфейса */
export type Lang = "ru" | "uz";
